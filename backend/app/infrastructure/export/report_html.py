_environment = Environment(
    autoescape=select_autoescape(default=True, default_for_string=True),
    trim_blocks=True,
    lstrip_blocks=True,
)
_template = _environment.from_string(_TEMPLATE)


def render_report_html(report: ScanReportData) -> str:
    scan = report.scan
    return _template.render(
        scan_id=str(scan.id),
        generated_at=_timestamp(report.generated_at),
        source_label=_SOURCE_LABELS[scan.source_type],
        status=scan.status.value,
        error_message=scan.error_message,
        created_at=_timestamp(scan.created_at),
        completed_at=_timestamp(scan.completed_at) if scan.completed_at else None,
        total_lines=sum(file.loc for file in report.files),
        severity_counts=[
            (severity.value, count) for severity, count in report.severity_counts.items()
        ],
        files=[
            {"path": file.relative_path, "language": file.language, "lines": file.loc}
            for file in report.files
        ],
        findings=[_finding_context(finding) for finding in report.findings],
    )


def _finding_context(finding: Finding) -> dict[str, Any]:
    location = finding.location
    lines = (
        f"line {location.line_start}"
        if location.line_start == location.line_end
        else f"lines {location.line_start}-{location.line_end}"
    )
    number_width = len(str(location.line_end))
    return {
        "title": finding.title,
        "severity": finding.severity.value,
        "confidence": f"{finding.confidence:.0%}",
        "location": f"{location.file_path}, {lines}",
        "explanation": finding.explanation,
        "recommendation": finding.recommendation,
        "fixed_code": finding.fixed_code,
        "snippet_lines": [
            {"number": str(number).rjust(number_width), "text": text}
            for number, text in enumerate(
                split_lines(finding.vulnerable_snippet), start=location.line_start
            )
        ],
        "references": [
            {"id": reference.ref_id, "title": reference.title, "url": reference.url}
            for reference in finding.references
        ],
    }


def _timestamp(value: Any) -> str:
    return str(value.strftime("%Y-%m-%d %H:%M UTC"))
