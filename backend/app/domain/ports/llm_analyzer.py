"""Port for the RAG-grounded LLM analysis step.

Deliberately returns findings *without* `id`, `scan_id`, `scan_file_id`,
`created_at`, or `vulnerable_snippet`: those are either generated by the use
case or sliced directly from the chunk's own source text (never trusted
verbatim from the LLM, which could paraphrase or mangle it).
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass

from app.domain.ports.knowledge_retriever import RetrievedKnowledge
from app.domain.value_objects.code_chunk import CodeChunk
from app.domain.value_objects.severity import Severity


@dataclass(frozen=True, slots=True)
class AnalyzedFinding:
    title: str
    cwe_id: str | None
    owasp_category: str | None
    attack_technique_id: str | None
    severity: Severity
    confidence: float
    line_start: int
    line_end: int
    explanation: str
    recommendation: str
    fixed_code: str | None


class LLMAnalyzer(ABC):
    @abstractmethod
    async def analyze(
        self, chunk: CodeChunk, context: list[RetrievedKnowledge]
    ) -> list[AnalyzedFinding]:
        """Asks the LLM to review one code chunk, grounded by the retrieved
        knowledge-base excerpts in `context`. Must itself validate the raw
        LLM output against the expected JSON shape and retry on failure
        (see the adapter's docstring) - callers get back either a clean
        list of findings or an exception, never malformed data."""
